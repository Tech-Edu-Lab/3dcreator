// 図面の点検結果を、生徒に伝えることば（赤ペンのコメント）にする。

export const VIEW_LABEL = { front: '正面図', top: '平面図', side: '右側面図' };

const NO_MATCH_TEXT = {
  'front:V': '正面図の赤いたての線と同じ左右の位置に、平面図にもたての線があるはずです。',
  'front:H': '正面図の赤いよこの線と同じ高さに、右側面図にもよこの線があるはずです。',
  'top:V': '平面図の赤いたての線と同じ左右の位置に、正面図にもたての線があるはずです。',
  'top:H': '平面図の赤いよこの線と同じ奥行きの位置に、右側面図ではたての線があるはずです。',
  'side:V': '右側面図の赤いたての線と同じ奥行きの位置に、平面図ではよこの線があるはずです。',
  'side:H': '右側面図の赤いよこの線と同じ高さに、正面図にもよこの線があるはずです。',
};

/**
 * issue（code と数値）に title / text をつけて返す。
 * T: 板の厚さ（マス）
 */
export function describeIssue(issue, T = 1) {
  const V = VIEW_LABEL[issue.view] || '';
  const O = VIEW_LABEL[issue.other] || '';
  let title = '', text = '';
  switch (issue.code) {
    case 'EMPTY_ALL':
      title = '図面がまだありません';
      text = '正面図・平面図・右側面図をかくか、かいた用紙を読みこみましょう。';
      break;
    case 'EMPTY_VIEW':
      title = `${V}がありません`;
      text = `${V}のわくに図がかかれていません。正面図・平面図・右側面図の3つがそろうと立体にできます。`;
      break;
    case 'STRAY':
      title = `${V}に、図からはなれた線があります`;
      text = '赤い線は、図とつながっていません。いらない線なら消しましょう。';
      break;
    case 'DANGLING':
      title = `${V}の線がとぎれています`;
      text = '赤い丸のところで線が止まっています。ほかの線につながるまでのばすか、いらない線なら消しましょう。';
      break;
    case 'WIDTH_MISMATCH':
      title = '正面図と平面図のはばがちがいます';
      text = `正面図のはばは${issue.front}マス、平面図のはばは${issue.top}マスです。同じ立体を見た図なので、左右のはばは同じになります。`;
      break;
    case 'ALIGN_X':
      title = '平面図の位置がずれています';
      text = `平面図が、正面図より${issue.shift > 0 ? '右' : '左'}に${Math.abs(issue.shift)}マスずれています。平面図は、正面図の真上にそろえてかきます。`;
      break;
    case 'HEIGHT_MISMATCH':
      title = '正面図と右側面図の高さがちがいます';
      text = `正面図の高さは${issue.front}マス、右側面図の高さは${issue.side}マスです。同じ立体を見た図なので、高さは同じになります。`;
      break;
    case 'ALIGN_Z':
      title = '右側面図の位置がずれています';
      text = `右側面図が、正面図より${issue.shift > 0 ? '上' : '下'}に${Math.abs(issue.shift)}マスずれています。右側面図は、正面図の真横にそろえてかきます。`;
      break;
    case 'DEPTH_MISMATCH':
      title = '平面図と右側面図の奥行きがちがいます';
      text = `平面図の奥行き（たての長さ）は${issue.top}マス、右側面図の奥行き（よこの長さ）は${issue.side}マスです。同じ立体を見た図なので、奥行きは同じになります。`;
      break;
    case 'NO_MATCH':
      title = `${V}の線に対応する線が、${O}にありません`;
      text = `${NO_MATCH_TEXT[`${issue.view}:${issue.kind}`]}その向きから見えない線は、かくれ線（破線）でかきます。`;
      break;
    case 'DEPTH_MIRRORED':
      title = '平面図と右側面図で、手前と奥が逆になっていませんか';
      text = 'どちらかの図をうら返すと、2つの図が合います。第三角法では、平面図は下側（正面図に近い側）が手前、右側面図は左側（正面図に近い側）が手前になります。';
      break;
    case 'SHOULD_DASH':
      title = `${V}に、かくれ線（破線）にする線があります`;
      text = '赤い線は、この向きから見ると手前の板にかくれて見えません。かくれ線（破線）でかき直しましょう。';
      break;
    case 'SHOULD_SOLID':
      title = `${V}に、実線にする線があります`;
      text = '赤い線は、この向きから見える線です。実線でかき直しましょう。';
      break;
    case 'UNEXPLAINED':
      title = `${V}に、立体と合わない線があります`;
      text = '赤い線は、ほかの2つの図と合わせて考えると、立体のどの辺にもあたりません。よぶんな線ではないか、ほかの図にかきわすれた線がないか、たしかめましょう。';
      break;
    case 'MISSING':
      title = `${V}に、たりない線があります`;
      text = '赤い位置に線がたりません。ほかの2つの図と見くらべて、線をかきたしましょう。';
      break;
    case 'NOT_BOARD_THICK':
      title = '板の厚さがかかれていません';
      text = `赤くぬった部分は、厚さ${T}マスの板ではなく、大きなかたまりになっています。板を1枚ずつ、厚さ${T}マスの細長い長方形でかきましょう。（たな板などを線1本でかいていませんか？）`;
      if (issue.hidden) text += '板の厚さがどの図からも見えないときは、かくれ線（破線）で厚さをかきます。';
      break;
    case 'HIDDEN_JOINT':
      title = '見えない所の形が決まりません';
      text = '赤くぬった所は、いまの図面からは、どちらの板がそこまでのびているのか（または、そこに板があるのか）が決まりません。このままでは組み立て方が分かりません。オレンジの破線は、考えられるかくれ線です。あなたの作品に合うものを、かくれ線（破線）でかきましょう。どれも合わないときは、赤い所にかくれている板を、作品のとおりにかくれ線でかきます。';
      break;
    case 'HIDDEN_MORE':
      title = 'かくれ線がたりなくて、形を決めきれません';
      text = '板の数が多く、見えない所の組み立て方がいく通りも考えられます。ほかの板にかくれている板の線を、右側面図や平面図に、かくれ線（破線）でかきたしましょう。';
      break;
    case 'FLAT_SEAM':
      title = '板の厚さがかかれていない線があります';
      text = `赤い線は、厚さのない線です。このままだと、同じ平面にならんだ2枚の板のつなぎ目と読めてしまいます。たな板や仕切りなら、厚さ${T}マスの細長い長方形でかきましょう。本当に2枚の板をならべるときは、オレンジの破線の所に、つなぎ目のかくれ線をかきましょう。`;
      break;
    case 'NO_THICKNESS':
      title = '厚さの分からない板があります';
      text = `赤くぬった板は、広い面だけがかかれていて、厚さがどの図からも分かりません（板を横から見た面が、ほかの板にかくれています）。ほかの図に、この板の厚さ${T}マスぶんを、かくれ線（破線）でかきましょう。`;
      break;
    case 'BOARD_END':
      title = '板のはしか、厚さのない線か、決まりません';
      text = `赤い線は「板がここで終わっていて、その先には何もない」と読めますが、たな板などの厚さをかきわすれた線かもしれません。たな板や仕切りなら、厚さ${T}マスの細長い長方形でかきましょう。板が本当にここで終わっているなら、オレンジの破線の所に、板のはしのかくれ線をかきましょう。`;
      break;
    case 'HIDDEN_UNEXPLAINED':
      title = `${V}に、立体と合わないかくれ線があります`;
      text = '赤いかくれ線は、見えている板のどの辺にもあたりません。実線の位置とくらべて、たしかめましょう。まるごとかくれた板をかくときは、3つの図すべてに、その板をかくれ線でかきます。';
      break;
    case 'INCONSISTENT_VISIBLE':
      title = '見える線（実線）どうしが合いません';
      text = '実線だけで考えても、3つの図に合う立体がありません。同じ板の線が、正面図・平面図・右側面図で同じ位置にあるか、見えない線を実線でかいていないか、たしかめましょう。';
      break;
    case 'NOT_BOARD_JOINED':
      title = '板と板のつなぎ目がかかれていません';
      text = '赤くぬった部分は、何枚かの板がつながって1つになっています。どの板がどこまでのびているのかが分からないので、組み立て方が決まりません。板と板のつなぎ目に線をかきましょう。';
      break;
    case 'NOT_BOARD_THIN':
      title = '板の厚さよりうすい部分があります';
      text = `赤くぬった部分は、板の厚さ（${T}マス）よりうすくなっています。板の厚さを${T}マスにそろえてかきましょう。`;
      break;
    case 'FLOATING':
      title = 'ほかの板にふれていない板があります';
      text = '赤くぬった板は、どの板にもふれていません。このままでは固定できないので、組み立てられません。となりの板にとどくまでのばしましょう。';
      break;
    case 'TOO_COMPLEX':
      title = '図面が複雑で、立体を決められませんでした';
      text = '線の数をへらして、もう一度ためしてください。';
      break;
    default:
      title = '図面をたしかめましょう';
      text = '3つの図がうまく合わず、立体にできませんでした。';
  }
  return { ...issue, title, text };
}
